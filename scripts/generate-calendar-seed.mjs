// Usage: node scripts/generate-calendar-seed.mjs  ->  writes supabase/seed_calendar.sql
// Reads the Hijri month anchors and the Fatemi occasions table straight out of index.html,
// so the database holds exactly what the demo showed. Re-run it whenever that table changes.
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");

const from = html.indexOf("const G=(y,m,d)");
const to = html.indexOf("// Look up every occasion");
if (from < 0 || to < 0) throw new Error("Could not find the calendar block in index.html");

const code = `const H=36e5,D=24*H;\n${html.slice(from, to)}\n;({hijriMonths,hijriYears,E})`;
const { hijriMonths, hijriYears, E } = vm.runInNewContext(code);

const q = (v) => (v == null ? "null" : "'" + String(v).replace(/'/g, "''") + "'");
const ymd = (ts) => {
  const d = new Date(ts); // anchors are built with local noon, so local getters round-trip exactly
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
};

const monthRows = [];
for (const yr of hijriYears)
  yr.anchors.forEach((a, i) => monthRows.push(`(${yr.y}, ${i}, ${q(hijriMonths[i])}, '${ymd(a)}', ${yr.lens[i]})`));

const occRows = [];
for (const key of Object.keys(E).sort((a, b) => {
  const [am, ad] = a.split("-").map(Number), [bm, bd] = b.split("-").map(Number);
  return am - bm || ad - bd;
})) {
  const [m, d] = key.split("-").map(Number);
  for (const o of E[key]) occRows.push(`(${m}, ${d}, ${q(o.n)}, ${q(o.loc)})`);
}

const sql = `-- GENERATED by scripts/generate-calendar-seed.mjs from index.html — do not edit by hand.
-- Re-runnable: replaces the calendar tables' contents. Run in the Supabase SQL editor.
begin;
delete from public.hijri_months;
insert into public.hijri_months (hijri_year, month_idx, month_name, starts_on, length_days) values
${monthRows.join(",\n")};

delete from public.calendar_occasions;
insert into public.calendar_occasions (month_idx, day, name, location) values
${occRows.join(",\n")};
commit;
`;
fs.writeFileSync(path.join(root, "supabase", "seed_calendar.sql"), sql);
console.log(`hijri_months: ${monthRows.length} rows, calendar_occasions: ${occRows.length} rows`);
